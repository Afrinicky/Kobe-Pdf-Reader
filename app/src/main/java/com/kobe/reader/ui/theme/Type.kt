/**
 * Type scale.
 *
 * Uses the platform sans (Roboto) rather than bundling a typeface: an extra
 * ~300 KB of font in an app whose selling point is being small and fast is a bad
 * trade, and the system font is what every other Android app the user has looks
 * like.
 *
 * The scale is slightly tighter than Material's default. File lists are the main
 * screen of this app, and Acrobat's own lists are dense - more rows visible
 * without scrolling is worth more here than generous leading.
 */
