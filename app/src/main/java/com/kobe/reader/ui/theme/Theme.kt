@Composable
fun KobeTheme(
    themePreference: ThemePreference = ThemePreference.System,
    /**
     * Off by default. Acrobat's red *is* the brand; letting the wallpaper
     * recolour it would make the app unrecognisable. Offered as a setting for
     * people who want their whole phone to match.
     */
    useDynamicColor: Boolean = false,
    content: @Composable () -> Unit,
) {
    val darkTheme = when (themePreference) {
        ThemePreference.System -> isSystemInDarkTheme()
        ThemePreference.Light -> false
        ThemePreference.Dark -> true
    }

    val context = LocalContext.current
    val colorScheme = when {
        useDynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S ->
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)

        darkTheme -> DarkColors
        else -> LightColors
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window ?: return@SideEffect
            // Edge-to-edge is set up in MainActivity; this only keeps the status
            // bar icons legible when the theme flips.
            WindowCompat.getInsetsController(window, view)
                .isAppearanceLightStatusBars = !darkTheme
            WindowCompat.getInsetsController(window, view)
                .isAppearanceLightNavigationBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = KobeTypography,
        shapes = KobeShapes,
        content = content,
    )
}

/** Reader chrome colours, which sit outside the Material scheme on purpose. */
object ReaderColors {
    val backdrop: Color @Composable get() = if (isSystemInDarkTheme()) ReaderBackdropDark else ReaderBackdrop
    val pageBorder: Color = PageBorder
}
